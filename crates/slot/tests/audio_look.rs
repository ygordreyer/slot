fn samples(path: impl AsRef<Path>) -> Vec<f32> {
    std::fs::read(path)
        .unwrap()
        .chunks_exact(4)
        .map(|b| f32::from_le_bytes(b.try_into().unwrap()))
        .collect()
}
fn compare(label: &str, got: &[f32], want: &[f32], tolerance: f32) {
    assert_eq!(got.len(), want.len(), "{label} length");
    let max = got
        .iter()
        .zip(want)
        .map(|(a, b)| (a - b).abs())
        .fold(0.0f32, f32::max);
    assert!(got.iter().all(|x| x.is_finite()));
    println!("{label}: max absolute difference {max:.9e}");
    assert!(max < tolerance, "{label}: {max} >= {tolerance}");
}
fn stage(name: &str) -> DspConfig {
    let config = if name == "chain" {
        OWNER.to_owned()
    } else {
        format!(
            "filters = 1\nfilter0 = {name}\n{}",
            OWNER
                .lines()
                .filter(|line| {
                    let line = line.trim();
                    line.starts_with("eq_")
                        || line.starts_with("reverb_")
                        || line.starts_with("iir_")
                        || line.starts_with("panning_")
                })
                .collect::<Vec<_>>()
                .join("\n")
        )
    };
    DspConfig::parse(&config).unwrap()
}
fn check_reference(dir: &Path) {
    let input = samples(dir.join("input.f32le"));
    for name in ["eq", "reverb", "iir", "panning", "chain"] {
        let mut dsp = stage(name).build(32768.0).unwrap();
        let mut got = Vec::new();
        dsp.process(&input, &mut |f| got.extend(f));
        compare(
            name,
            &got,
            &samples(dir.join(format!("{name}.f32le"))),
            1e-4,
        );
    }
    for change in [false, true] {
        let name = if change { "sinc_change" } else { "sinc" };
        let mut r = SincResampler::new(32768.0, 48000.0, SincQuality::Higher);
        let mut got = Vec::new();
        let half = input.len() / 2;
        r.process(&input[..half], &mut |f| got.extend(f));
        if change {
            r.set_ratio(1.004);
        }
        r.process(&input[half..], &mut |f| got.extend(f));
        compare(
            name,
            &got,
            &samples(dir.join(format!("{name}.f32le"))),
            1e-4,
        );
    }
}

