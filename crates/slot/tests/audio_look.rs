#[test]
#[ignore = "requires python3 crates/slot/tests/audio_reference.py"]
fn reference_live_equivalence() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../target/audio-reference");
    check_reference(&dir);
    let input = samples(dir.join("input.f32le"));
    for (block, name) in [(2048, "sinc_fast_forward"), (1, "sinc_fast_forward_single")] {
        let mut r = SincResampler::new(32768.0, 48000.0, SincQuality::Higher);
        for (part, input) in input.chunks(2048 * 2).enumerate() {
            r.set_ratio(if part == 1 || part == 2 {
                1.0 / 6.0
            } else {
                1.0
            });
            let mut got = Vec::new();
            let warmup = if block == 1 && (part == 1 || part == 3) {
                1800 * 2
            } else {
                0
            };
            r.process(&input[..warmup], &mut |f| got.extend(f));
            for chunk in input[warmup..].chunks(block * 2) {
                r.process(chunk, &mut |f| got.extend(f));
            }
            let want = samples(dir.join(format!("{name}_part{part}.f32le")));
            assert!((got.len() as isize - want.len() as isize).abs() <= 2);
            // C repeats or skips old samples at call boundaries during fades.
            // Compare the unchanged kernels after warmup; Rust's transition
            // pairing is checked against bulk output and continuity below.
            let tail = if part == 0 || part == 2 {
                want.len()
            } else {
                64 * 2
            };
            assert!(got.len() >= tail);
            compare(
                &format!("{name} part {part} settled"),
                &got[got.len() - tail..],
                &want[want.len() - tail..],
                1e-4,
            );
        }
    }
}

