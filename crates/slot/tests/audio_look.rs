struct AllocationCounter;
std::thread_local! {
    static ALLOCATIONS: std::cell::Cell<Option<usize>> = const { std::cell::Cell::new(None) };
}
unsafe impl std::alloc::GlobalAlloc for AllocationCounter {
    unsafe fn alloc(&self, layout: std::alloc::Layout) -> *mut u8 {
        let _ = ALLOCATIONS.try_with(|counter| {
            if let Some(count) = counter.get() {
                counter.set(Some(count + 1));
            }
        });
        unsafe { std::alloc::System.alloc(layout) }
    }
    unsafe fn dealloc(&self, pointer: *mut u8, layout: std::alloc::Layout) {
        unsafe { std::alloc::System.dealloc(pointer, layout) }
    }
    unsafe fn realloc(&self, pointer: *mut u8, layout: std::alloc::Layout, size: usize) -> *mut u8 {
        let _ = ALLOCATIONS.try_with(|counter| {
            if let Some(count) = counter.get() {
                counter.set(Some(count + 1));
            }
        });
        unsafe { std::alloc::System.realloc(pointer, layout, size) }
    }
}
#[global_allocator]
static ALLOCATOR: AllocationCounter = AllocationCounter;

#[test]
fn look_processing_does_not_allocate() {
    let look = AudioLook {
        resampler: Some(ResamplerKind::Sinc),
        quality: Some(SincQuality::Higher),
        dsp: Some(stage("chain")),
        gain_db: Some(-2.0),
        ..AudioLook::default()
    };
    let mut p = LookProcessor::new(&look, 32768.0, 32768.0, 48000).unwrap();
    let mut count = 0;
    ALLOCATIONS.with(|c| c.set(Some(0)));
    for ratio in [1.004, 1.0 / 6.0, 1.0, 1.0 / 6.0, 1.004] {
        for _ in 0..16 {
            p.process(&[1200; 1024], ratio, 0.81, &mut |out| {
                count += out.len();
                std::hint::black_box(out);
            });
        }
    }
    let allocations = ALLOCATIONS.with(|c| c.replace(None).unwrap());
    assert_eq!(allocations, 0);
    assert!(count > 20000);
}

