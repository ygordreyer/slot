#[test]
fn fast_forward_crossfade_is_independent_of_call_size() {
    let input = samples(Path::new(FIXTURES).join("input.f32le"));
    let render = |quality: SincQuality, block: usize| {
        let mut r = SincResampler::new(32768.0, 48000.0, quality);
        let mut out = Vec::new();
        for (part, input) in input.chunks(1024 * 2).cycle().take(12).enumerate() {
            r.set_ratio(if (3..9).contains(&part) {
                1.0 / 6.0
            } else {
                1.0
            });
            for chunk in input.chunks(block * 2) {
                r.process(chunk, &mut |f| out.extend(f));
            }
        }
        out
    };
    for quality in [
        SincQuality::Lowest,
        SincQuality::Lower,
        SincQuality::Normal,
        SincQuality::Higher,
        SincQuality::Highest,
    ] {
        let bulk = render(quality, 1024);
        for block in [1, 7, 64] {
            // Equal stream positions should have only floating-point rounding error,
            // not a sample of phase error or an unblended cold-path discontinuity.
            compare(
                &format!("fast-forward {quality:?} {block}-frame calls"),
                &render(quality, block),
                &bulk,
                1e-6,
            );
        }
    }
}

#[test]
fn fast_forward_crossfade_keeps_a_constant_signal_continuous() {
    let mut r = SincResampler::new(32768.0, 48000.0, SincQuality::Higher);
    let mut out = Vec::new();
    r.process(&vec![0.2; 4096 * 2], &mut |f| out.push(f[0]));
    out.clear();
    for ratio in [1.0 / 6.0, 1.0] {
        r.set_ratio(ratio);
        for _ in 0..4096 {
            r.process(&[0.2; 2], &mut |f| out.push(f[0]));
        }
    }
    let jump = out
        .windows(2)
        .map(|s| (s[1] - s[0]).abs())
        .fold(0.0f32, f32::max);
    println!("DC fast-forward maximum adjacent jump: {jump:.9e}");
    assert!(jump < 1e-3, "DC discontinuity: {jump}");
    assert!(out.iter().all(|&s| (s - 0.2).abs() < 1e-3));
}

#[test]
fn interrupted_fast_forward_crossfade_keeps_dc_continuous() {
    for (rate, quality, fast_frames) in [
        (8000.0, SincQuality::Highest, 3294),
        (48000.0, SincQuality::Higher, 129),
    ] {
        for block in [1, 7, 64, 20000] {
            let mut r = SincResampler::new(32768.0, rate, quality);
            let input = vec![0.2; 20000 * 2];
            r.process(&input, &mut |_| {});
            let mut out = Vec::new();
            for (ratio, frames) in [(1.0 / 6.0, fast_frames), (1.0, 20000)] {
                r.set_ratio(ratio);
                for chunk in input[..frames * 2].chunks(block * 2) {
                    r.process(chunk, &mut |f| out.extend(f));
                }
            }
            let deviation = out.iter().map(|&s| (s - 0.2).abs()).fold(0.0, f32::max);
            println!("{rate} Hz {quality:?} {block}-frame calls: DC deviation {deviation:.9e}");
            assert!(
                deviation < 1e-3,
                "{rate} Hz {quality:?} {block}-frame calls: DC deviation {deviation}"
            );
        }
    }
}

#[test]
fn interrupted_fast_forward_crossfades_are_identical_across_call_sizes() {
    let source = samples(Path::new(FIXTURES).join("input.f32le"));
    let input: Vec<f32> = source.iter().copied().cycle().take(40000 * 2).collect();
    let render = |rate, quality, block: usize| {
        let mut r = SincResampler::new(32768.0, rate, quality);
        let mut out = Vec::new();
        for (ratio, frames) in [
            (1.0, 8192),
            (1.0 / 6.0, 17),
            (1.0, 40000),
            (1.0 / 6.0, 40000),
            (1.0, 17),
            (1.0 / 6.0, 40000),
            (1.0, 40000),
        ] {
            r.set_ratio(ratio);
            for chunk in input[..frames * 2].chunks(block * 2) {
                r.process(chunk, &mut |f| out.extend(f));
            }
        }
        out
    };
    for rate in [8000.0, 48000.0] {
        for quality in [
            SincQuality::Lowest,
            SincQuality::Lower,
            SincQuality::Normal,
            SincQuality::Higher,
            SincQuality::Highest,
        ] {
            let bulk = render(rate, quality, 40000);
            for block in [1, 7, 64] {
                let got = render(rate, quality, block);
                assert_eq!(
                    got.len(),
                    bulk.len(),
                    "{rate} Hz {quality:?} {block}-frame calls: length"
                );
                assert!(
                    got == bulk,
                    "{rate} Hz {quality:?} {block}-frame calls: first mismatch {:?}",
                    got.iter().zip(&bulk).position(|(a, b)| a != b)
                );
            }
        }
    }
}

#[test]
fn fast_forward_rejects_content_above_output_nyquist() {
    let rms = |hz: f64| {
        let mut r = SincResampler::new(32768.0, 48000.0, SincQuality::Higher);
        r.set_ratio(1.0 / 6.0);
        let input: Vec<f32> = (0..16384)
            .flat_map(|i| {
                let value = (std::f64::consts::TAU * hz * i as f64 / 32768.0).sin() as f32;
                [value, value]
            })
            .collect();
        let mut out = Vec::new();
        r.process(&input, &mut |f| out.push(f[0]));
        let settled = &out[2048..];
        (settled.iter().map(|&x| x as f64 * x as f64).sum::<f64>() / settled.len() as f64).sqrt()
    };
    assert!(rms(1000.0) > 0.65);
    assert!(rms(8000.0) < 1e-4);
}

