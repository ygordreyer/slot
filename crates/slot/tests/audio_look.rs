#[test]
fn block_size_invariance() {
    let input = samples(Path::new(FIXTURES).join("input.f32le"));
    let mut expected_dsp = Vec::new();
    stage("chain")
        .build(32768.0)
        .unwrap()
        .process(&input, &mut |f| expected_dsp.extend(f));
    for quality in [
        SincQuality::Lowest,
        SincQuality::Lower,
        SincQuality::Normal,
        SincQuality::Higher,
        SincQuality::Highest,
    ] {
        let mut expected_sinc = Vec::new();
        SincResampler::new(32768.0, 48000.0, quality)
            .process(&input, &mut |f| expected_sinc.extend(f));
        for size in [1, 7, 512, input.len() / 2] {
            let mut dsp = stage("chain").build(32768.0).unwrap();
            let mut sinc = SincResampler::new(32768.0, 48000.0, quality);
            let (mut got_dsp, mut got_sinc) = (Vec::new(), Vec::new());
            for block in input.chunks(size * 2) {
                dsp.process(block, &mut |f| got_dsp.extend(f));
                sinc.process(block, &mut |f| got_sinc.extend(f));
            }
            compare("DSP block invariance", &got_dsp, &expected_dsp, 1e-6);
            compare("sinc block invariance", &got_sinc, &expected_sinc, 1e-6);
        }
    }
}

